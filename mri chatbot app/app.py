from flask import Flask, render_template, request, redirect, url_for, flash, send_from_directory, jsonify, session
import os
from werkzeug.utils import secure_filename
import tensorflow as tf
from PIL import Image
import numpy as np
import json

app = Flask(__name__)
app.secret_key = 'supersecretkey'
app.config['UPLOAD_FOLDER'] = 'uploads'
app.config['MAX_CONTENT_LENGTH'] = 16 * 1024 * 1024  # Limit 16MB

# Load the model
brain_tumor_model = tf.keras.models.load_model('model1/effnet.keras')

# Labels
tumor_labels = ['Glioma Tumor', 'No Tumor', 'Meningioma Tumor', 'Pituitary Tumor']

# Function to preprocess the image
def preprocess_image(image_path):
    image = Image.open(image_path).resize((150, 150))
    image = np.array(image)
    image = np.expand_dims(image, axis=0)
    return image

# Save predictions to a file
def save_prediction(filename, prediction, model_id):
    predictions_file = f'predictions{model_id}.json'
    if os.path.exists(predictions_file):
        with open(predictions_file, 'r') as f:
            predictions = json.load(f)
    else:
        predictions = {}

    predictions[filename] = prediction

    with open(predictions_file, 'w') as f:
        json.dump(predictions, f)

def clear_upload_folder():
    """Remove all files from the uploads folder."""
    for file in os.listdir(app.config['UPLOAD_FOLDER']):
        file_path = os.path.join(app.config['UPLOAD_FOLDER'], file)
        if os.path.isfile(file_path):
            os.remove(file_path)

@app.route('/uploads/<filename>')
def uploaded_file(filename):
    return send_from_directory(app.config['UPLOAD_FOLDER'], filename)

@app.route('/', methods=['GET', 'POST'])
def index():
    if request.method == 'POST':
        if 'file' not in request.files:
            flash('No file part')
            return redirect(request.url)
        file = request.files['file']
        if file.filename == '':
            flash('No selected file')
            return redirect(request.url)
        if file:
            # Clear the uploads folder before saving the new file
            clear_upload_folder()

            filename = secure_filename(file.filename)
            file_path = os.path.join(app.config['UPLOAD_FOLDER'], filename)
            file.save(file_path)

            # Process the image
            image = preprocess_image(file_path)

            # Prediction for the model
            prediction = brain_tumor_model.predict(image)
            predicted_class = tumor_labels[np.argmax(prediction)]

            session['mri_prediction'] = predicted_class

            # Save predictions
            save_prediction(filename, predicted_class, 1)

            return redirect(url_for('index'))

    # Load the list of uploaded files
    uploaded_files = os.listdir(app.config['UPLOAD_FOLDER'])

    # Load predictions for the model
    model_predictions = {}
    if os.path.exists('predictions1.json'):
        with open('predictions1.json', 'r') as f:
            model_predictions = json.load(f)

    # Combine predictions into one dictionary
    predictions = {
        filename: {
            'model1': model_predictions.get(filename, 'No prediction yet'),
        }
        for filename in uploaded_files
    }

    return render_template('index.html', predictions=predictions, uploaded_files=uploaded_files)

from flask import send_from_directory

@app.route('/chatbot/<path:filename>')
def serve_chatbot_files(filename):
    return send_from_directory('chatbot', filename)

# API for chatbot requests
@app.route('/chat', methods=['POST'])
def chat():
    from chatbot.chatbot_logic import analyze_question

    # Log the incoming request
    request_data = request.json
    print("Received data from frontend:", request_data)  # Debugging

    user_question = request_data.get("question", "")
    if not user_question:
        return jsonify({"error": "No question provided"}), 400

    mri_prediction = session.get('mri_prediction', 'No prediction available')
    print("MRI model result passed to chatbot:", mri_prediction)

    # Process the question in chatbot_logic.py
    chatbot_response = analyze_question(user_question, mri_prediction)

    print("Response generated by chatbot:", chatbot_response)  # Debugging

    # Check if chatbot_response is None
    if chatbot_response is None:
        chatbot_response = "There was a problem with the chatbot response."

    # Return the response as JSON
    return jsonify({"response": chatbot_response})


if __name__ == '__main__':
    if not os.path.exists(app.config['UPLOAD_FOLDER']):
        os.makedirs(app.config['UPLOAD_FOLDER'])
    app.run(debug=True)
